/**
 * Chart px → A4 page for one letter, centred. Letters keep chart size where it fits;
 * tiny ones (Ha, Hamzah) are scaled up and very wide ones (Syin, Kaf) down.
 * @param {number[][]} pts
 */
function toPage(pts) {
  const marginX = 70
  const marginY = 130
  const w = A4_W - marginX * 2
  const h = A4_H - marginY * 2 - 40
  const xs = pts.map((p) => p[0])
  const ys = pts.map((p) => p[1])
  const minx = Math.min(...xs)
  const maxx = Math.max(...xs)
  const miny = Math.min(...ys)
  const maxy = Math.max(...ys)
  const fill = Math.max((maxx - minx) / w, (maxy - miny) / h)
  const k = Math.min(Math.max(1, 0.5 / fill), 1 / fill)
  const cx = marginX + w / 2
  const cy = marginY + h / 2
  const ox = (minx + maxx) / 2
  const oy = (miny + maxy) / 2
  return { k, map: (x, y) => ({ x: cx + (x - ox) * k, y: cy + (y - oy) * k }) }
}

/**
 * Catmull-Rom spline through points; half-width is interpolated linearly.
 * @param {Point[]} P
 */
function spline(P, steps = 6) {
  if (P.length < 3) return P
  /** @type {Point[]} */
  const out = [P[0]]
  for (let i = 0; i < P.length - 1; i += 1) {
    const p0 = P[i - 1] ?? P[i]
    const p1 = P[i]
    const p2 = P[i + 1]
    const p3 = P[i + 2] ?? P[i + 1]
    for (let s = 1; s <= steps; s += 1) {
      const t = s / steps
      const t2 = t * t
      const t3 = t2 * t
      const f = (a, b, c, d) =>
        0.5 * (2 * b + (-a + c) * t + (2 * a - 5 * b + 4 * c - d) * t2 + (-a + 3 * b - 3 * c + d) * t3)
      out.push({ x: f(p0.x, p1.x, p2.x, p3.x), y: f(p0.y, p1.y, p2.y, p3.y), w: p1.w + (p2.w - p1.w) * t })
    }
  }
  return out
}

/** Pieces meet at sharp corners; each piece is smoothed on its own. */
function buildStroke(pieces, page) {
  /** @type {Point[]} */
  const out = []
  for (const flat of pieces) {
    const pts = []
    for (let i = 0; i < flat.length; i += 3) pts.push({ ...page.map(flat[i], flat[i + 1]), w: flat[i + 2] * page.k })
    const sm = spline(pts)
    out.push(...(out.length ? sm.slice(1) : sm))
  }
  return out
}

