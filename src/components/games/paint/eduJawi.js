/**
 * @param {string} ch
 * @returns {{ name: string, rumi: string, paths: Point[][], outline: Point[][], nuqtah: { x: number, y: number, r: number }[] } | null}
 */
export function getJawiLetter(ch) {
  const entry = LETTERS[ch]
  if (!entry) return null
  const [name, rumi, bodyKey, dots] = entry
  const body = BODIES[bodyKey]
  const pts = body.o.flatMap((loop) => loop.flatMap((_, i) => (i % 2 ? [] : [[loop[i], loop[i + 1]]])))
  for (let i = 0; i < dots.length; i += 3) {
    pts.push([dots[i] - dots[i + 2], dots[i + 1] - dots[i + 2]], [dots[i] + dots[i + 2], dots[i + 1] + dots[i + 2]])
  }
  const page = toPage(pts)
  const outline = body.o.map((loop) => loop.flatMap((_, i) => (i % 2 ? [] : [page.map(loop[i], loop[i + 1])])))
  const nuqtah = []
  for (let i = 0; i < dots.length; i += 3) nuqtah.push({ ...page.map(dots[i], dots[i + 1]), r: dots[i + 2] * page.k })
  const paths = body.s.map((pieces) => buildStroke(pieces, page))
  for (const d of nuqtah) paths.push([{ x: d.x, y: d.y, w: d.r }])
  return { name, rumi, paths, outline, nuqtah }
}

